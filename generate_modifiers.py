#!/usr/bin/env python3
"""Build modifiers.js from modifiers.json (Square modifier lists).

modifiers.json was read from the Square Dashboard > Items > Modifiers
for Beacon Pizza and Tap House (read-only, Nov 22 2026): 27 sets,
562 options with prices. This script just wraps it for the browser —
prices stay in dollars here, exactly as Square shows them; app.js
converts to integer cents.

Extra display fixes (beyond the ones recorded in modifiers.json):
the wing flavor "1/2 &1/2" and the half-flavor spellings get a space /
apostrophe / capital so they read cleanly on screen. Raw Square names
are kept as the keys, so lookups still match.

Re-run after modifiers.json changes (e.g. if the $310.00 Chicken
Bacon Ranch typo on Left Side 10" is fixed in Square).
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))

EXTRA_FIXES = {
    "1/2 &1/2": "1/2 & 1/2",
    "1/2 Vinces Wings": "1/2 Vince's Wings",
    "1/2 Spicy Dry rub": "1/2 Spicy Dry Rub",
}

HEADER = """/* Beacon POS — modifier data.
   Generated by generate_modifiers.py from modifiers.json (Square
   modifier lists, read from the Dashboard Nov 22 2026). Do not
   hand-edit prices here; fix them in Square, re-read modifiers.json,
   and re-run generate_modifiers.py.
   Prices are in dollars, exactly as Square lists them. A null price
   means Square's price field was blank — the app treats it as $0.00.
   NOTE: Left Side 10" "Chicken Bacon Ranch" is $310.00 in Square
   (every other size/side is $2.60-$3.25). Recorded as shown; do NOT
   "fix" it here — it changes only when Vince confirms the Square fix.
*/
window.BEACON_MODIFIERS = """

with open(os.path.join(HERE, "modifiers.json"), encoding="utf-8") as f:
    data = json.load(f)

fixes = dict(data.get("display_name_fixes", {}))
fixes.update(EXTRA_FIXES)

out = {
    "source": data.get("source", ""),
    "sets": data["sets"],
    "displayNameFixes": fixes,
}

with open(os.path.join(HERE, "modifiers.js"), "w", encoding="utf-8") as f:
    f.write(HEADER)
    json.dump(out, f, indent=2, ensure_ascii=False)
    f.write(";\n")

n_sets = len(out["sets"])
n_opts = sum(len(v) for v in out["sets"].values())
print(f"modifiers.js: {n_sets} sets, {n_opts} options")
